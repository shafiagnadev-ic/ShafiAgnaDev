  window.PORTFOLIO_I18N.setLanguage = function (lang, animate) {
    if (!this[lang]) lang = 'id';
    this.currentLang = lang;
    try { localStorage.setItem('agna-lang', lang); } catch (e) {}

    const dict = this[lang];
    const elements = document.querySelectorAll('[data-i18n]');

    const apply = () => {
      elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (!key || !dict[key]) return;
        const val = dict[key];
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          el.placeholder = val;
        } else if (val.includes('<')) {
          el.innerHTML = val;
        } else {
          el.textContent = val;
        }
      });
      document.querySelectorAll('.lang-btn').forEach(btn => {
        const active = btn.dataset.lang === lang;
        btn.classList.toggle('active', active);
        btn.setAttribute('aria-pressed', String(active));
      });
    };

    if (animate && document.body) {
      document.body.classList.add('lang-transition');
      setTimeout(() => {
        apply();
        setTimeout(() => document.body.classList.remove('lang-transition'), 200);
      }, 150);
    } else {
      apply();
    }
  };
